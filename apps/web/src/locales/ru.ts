/** Русское множественное число: 1 карта · 2 карты · 5 карт (11–14 → «много»).
 *  Число может прийти уже отформатированным («1 200») — берём только цифры. */
const pl = (n: string | number | undefined, one: string, few: string, many: string): string => {
  const x = Number(String(n ?? '').replace(/\D/g, '')) % 100;
  const d = x % 10;
  if (x >= 11 && x <= 14) return many;
  if (d === 1) return one;
  if (d >= 2 && d <= 4) return few;
  return many;
};

